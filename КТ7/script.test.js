const addToCart = require('./script');

test('Нельзя добавить товар, если его нет в наличии', () => {
    expect(addToCart(false, 1)).toBe("Ошибка: Товара нет в наличии");
});

test('Нельзя добавить товар с количеством 0', () => {
    expect(addToCart(true, 0)).toBe("Ошибка: Укажите количество");
});

test('Товар успешно добавляется, если он в наличии и количество > 0', () => {
    expect(addToCart(true, 5)).toBe("Товар добавлен в корзину");
});